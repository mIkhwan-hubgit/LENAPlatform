-- LENA, option B schema.
--
-- Run this once against the Neon database, from the Neon SQL Editor.
-- It is written to be safe to run more than once.
--
-- Two design notes.
--
-- Record payloads are jsonb rather than typed columns. The client's
-- shapes are still changing, and a column migration on every tweak is
-- not worth it at this stage. The columns that the server actually
-- reasons about, namely ownership, kind, time and deletion, are real
-- columns and are indexed.
--
-- Deletes are soft. A hard delete cannot be synced, because a second
-- device has no way to tell "deleted" from "not seen yet". The one
-- exception is account deletion, which is a real cascade.
-- ════════════════════════════════════════════════════════════════════

CREATE TABLE IF NOT EXISTS users (
  id            uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  email         text NOT NULL,
  email_norm    text NOT NULL UNIQUE,   -- lowercased and trimmed
  pw_hash       text NOT NULL,          -- scrypt, see api/_lib/auth.js
  display_name  text,
  created_at    timestamptz NOT NULL DEFAULT now(),
  last_login_at timestamptz,
  -- Simple brute-force brake. Cleared on a successful sign-in.
  failed_logins int NOT NULL DEFAULT 0,
  locked_until  timestamptz
);

-- Sessions hold only a hash of the cookie token, so a dump of this
-- table cannot be replayed as a login.
CREATE TABLE IF NOT EXISTS sessions (
  token_hash  text PRIMARY KEY,
  user_id     uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at  timestamptz NOT NULL DEFAULT now(),
  expires_at  timestamptz NOT NULL,
  user_agent  text
);
CREATE INDEX IF NOT EXISTS sessions_user_idx ON sessions(user_id);
CREATE INDEX IF NOT EXISTS sessions_exp_idx  ON sessions(expires_at);

-- One table for every synced record type. kind is one of
-- mood, sleep, screening, journal, safety_plan, prefs.
--
-- id is generated by the client, so a guest who later creates an
-- account can upload what they already have without collisions.
CREATE TABLE IF NOT EXISTS records (
  id          uuid NOT NULL,
  user_id     uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  kind        text NOT NULL,
  payload     jsonb NOT NULL,
  updated_at  timestamptz NOT NULL,
  deleted     boolean NOT NULL DEFAULT false,
  PRIMARY KEY (user_id, id)
);
CREATE INDEX IF NOT EXISTS records_sync_idx ON records(user_id, updated_at);
CREATE INDEX IF NOT EXISTS records_kind_idx ON records(user_id, kind);

ALTER TABLE records DROP CONSTRAINT IF EXISTS records_kind_check;
ALTER TABLE records ADD CONSTRAINT records_kind_check
  CHECK (kind IN ('mood','sleep','screening','journal','safety_plan','prefs'));

-- Per-day chat budget, so an authenticated endpoint cannot be used to
-- drain the API quota. day is a plain date in UTC.
CREATE TABLE IF NOT EXISTS chat_usage (
  user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  day     date NOT NULL,
  used    int  NOT NULL DEFAULT 0,
  PRIMARY KEY (user_id, day)
);

-- Housekeeping. Neon's free tier has no scheduler, so call this from
-- any endpoint occasionally, or run it by hand now and then.
CREATE OR REPLACE FUNCTION purge_expired_sessions() RETURNS void AS $$
  DELETE FROM sessions WHERE expires_at < now();
$$ LANGUAGE sql;

-- ── Sign in with Google (v36) ────────────────────────────────────────
-- google_sub is Google's permanent number for the account. An account
-- made with Google has no password, so pw_hash may now be empty.
ALTER TABLE users ALTER COLUMN pw_hash DROP NOT NULL;
ALTER TABLE users ADD COLUMN IF NOT EXISTS google_sub text;
ALTER TABLE users ADD COLUMN IF NOT EXISTS picture text;
CREATE UNIQUE INDEX IF NOT EXISTS users_google_sub_idx ON users(google_sub) WHERE google_sub IS NOT NULL;
